def mission_by_id(mission_id: str) -> Mission:
    for mission in MISSIONS:
        if mission.id == mission_id:
            return mission
    raise KeyError(mission_id)


def missions_for_level(level: int) -> tuple[Mission, ...]:
    return tuple(mission for mission in MISSIONS if mission.level == level)
